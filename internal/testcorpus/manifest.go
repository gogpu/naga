// Package testcorpus records and verifies the provenance of the test corpus
// under snapshot/testdata (ADR-006).
//
// A corpus tree (snapshot/testdata/rust, snapshot/testdata/rust-derived) carries
// a MANIFEST.json listing every file with its SHA-256 and git blob id. The
// manifest is written by the corpussync tool and checked by the snapshot tests,
// so a hand edit, a lost file or a stray file in a vendored tree fails CI.
// Files are hashed byte for byte: vendored data must match upstream exactly,
// line endings included.
package testcorpus

import (
	"bytes"
	"crypto/sha1" //nolint:gosec // git blob ids are SHA-1 by definition; integrity uses SHA-256
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"sort"
	"strconv"
	"strings"
)

const (
	// ManifestName is the manifest file at the root of a corpus tree.
	ManifestName = "MANIFEST.json"
	// ReadmeName is the human-written description of a corpus tree. It is ours,
	// not vendored, so the manifest does not cover it.
	ReadmeName = "README.md"
	// SchemaVersion is the manifest format version this package reads and writes.
	SchemaVersion = 1
)

// Kind says where the files of a corpus tree come from.
type Kind string

const (
	// KindVendored files are verbatim copies from the upstream repository.
	KindVendored Kind = "vendored"
	// KindDerived files were generated by running upstream code or tools.
	KindDerived Kind = "derived"
)

// Source describes the origin of a corpus tree.
type Source struct {
	// Repository is the upstream repository URL.
	Repository string `json:"repository"`
	// Commit is the full upstream commit the files were taken from, if a
	// single commit is known.
	Commit string `json:"commit,omitempty"`
	// CommitDate is the committer date of Commit (YYYY-MM-DD).
	CommitDate string `json:"commitDate,omitempty"`
	// Generator names the tool that produced derived files.
	Generator string `json:"generator,omitempty"`
	// Note records anything a reader needs to interpret the provenance.
	Note string `json:"note,omitempty"`
}

// File is one manifest entry.
type File struct {
	// Path is slash-separated and relative to the tree root.
	Path string `json:"path"`
	// SHA256 is the lowercase hex SHA-256 of the file content.
	SHA256 string `json:"sha256"`
	// GitBlob is the git blob id of the content; `git log --find-object=<id>`
	// in the upstream repository shows where the content came from.
	GitBlob string `json:"gitBlob"`
}

// Manifest lists every file of a corpus tree with its hashes.
type Manifest struct {
	Schema int    `json:"schema"`
	Kind   Kind   `json:"kind"`
	Source Source `json:"source"`
	// Files is sorted by Path, without duplicates.
	Files []File `json:"files"`
}

// GitBlobID returns the git object id of content stored as a blob.
func GitBlobID(content []byte) string {
	h := sha1.New() //nolint:gosec // git object ids are SHA-1, not a security boundary
	h.Write([]byte("blob " + strconv.Itoa(len(content)) + "\x00"))
	h.Write(content)
	return hex.EncodeToString(h.Sum(nil))
}

func hashFile(rel string, content []byte) File {
	sum := sha256.Sum256(content)
	return File{Path: rel, SHA256: hex.EncodeToString(sum[:]), GitBlob: GitBlobID(content)}
}

// isOwnFile reports whether rel is a file of the tree itself rather than corpus
// content: the manifest and the readme at the tree root.
func isOwnFile(rel string) bool {
	return rel == ManifestName || rel == ReadmeName
}

// withRoot opens dir as an os.Root, which confines every access to the tree,
// runs fn and closes the root, reporting both fn's and Close's errors.
func withRoot(dir string, fn func(root *os.Root) error) (err error) {
	root, err := os.OpenRoot(dir)
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, root.Close()) }()
	return fn(root)
}

// HashTree hashes every regular file under dir except the manifest and the
// readme at its root, sorted by path.
func HashTree(dir string) ([]File, error) {
	var files []File
	err := withRoot(dir, func(root *os.Root) error {
		return fs.WalkDir(root.FS(), ".", func(rel string, d fs.DirEntry, walkErr error) error {
			if walkErr != nil {
				return walkErr
			}
			if d.IsDir() || isOwnFile(rel) {
				return nil
			}
			if !d.Type().IsRegular() {
				return fmt.Errorf("%s: not a regular file", rel)
			}
			content, readErr := root.ReadFile(rel)
			if readErr != nil {
				return readErr
			}
			files = append(files, hashFile(rel, content))
			return nil
		})
	})
	if err != nil {
		return nil, fmt.Errorf("hash %s: %w", dir, err)
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	return files, nil
}

// Write stores the manifest as dir/MANIFEST.json. The output is deterministic:
// files sorted by path, two-space indentation, LF line endings, final newline.
func (m *Manifest) Write(dir string) error {
	sorted := *m
	sorted.Files = append([]File(nil), m.Files...)
	sort.Slice(sorted.Files, func(i, j int) bool { return sorted.Files[i].Path < sorted.Files[j].Path })
	if err := sorted.validate(); err != nil {
		return err
	}
	data, err := json.MarshalIndent(&sorted, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	return withRoot(dir, func(root *os.Root) error {
		return root.WriteFile(ManifestName, data, 0o644)
	})
}

// Load reads and validates dir/MANIFEST.json.
func Load(dir string) (*Manifest, error) {
	var data []byte
	err := withRoot(dir, func(root *os.Root) error {
		var readErr error
		data, readErr = root.ReadFile(ManifestName)
		return readErr
	})
	if err != nil {
		return nil, err
	}

	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var m Manifest
	if err := dec.Decode(&m); err != nil {
		return nil, fmt.Errorf("%s/%s: %w", dir, ManifestName, err)
	}
	if err := m.validate(); err != nil {
		return nil, fmt.Errorf("%s/%s: %w", dir, ManifestName, err)
	}
	return &m, nil
}

func (m *Manifest) validate() error {
	if m.Schema != SchemaVersion {
		return fmt.Errorf("unsupported schema %d (want %d)", m.Schema, SchemaVersion)
	}
	if m.Kind != KindVendored && m.Kind != KindDerived {
		return fmt.Errorf("unknown kind %q", m.Kind)
	}
	if m.Source.Repository == "" {
		return errors.New("source.repository is empty")
	}
	for i, f := range m.Files {
		if err := validatePath(f.Path); err != nil {
			return err
		}
		if i > 0 && m.Files[i-1].Path >= f.Path {
			return fmt.Errorf("files must be sorted by path without duplicates: %q after %q", f.Path, m.Files[i-1].Path)
		}
		if !isHex(f.SHA256, sha256.Size*2) {
			return fmt.Errorf("%s: sha256 %q is not %d lowercase hex digits", f.Path, f.SHA256, sha256.Size*2)
		}
		if !isHex(f.GitBlob, sha1.Size*2) {
			return fmt.Errorf("%s: gitBlob %q is not %d lowercase hex digits", f.Path, f.GitBlob, sha1.Size*2)
		}
	}
	return nil
}

// validatePath accepts clean, relative, slash-separated paths inside the tree
// that are not the tree's own files.
func validatePath(p string) error {
	if p == "" || strings.Contains(p, `\`) || !fs.ValidPath(p) || path.Clean(p) != p || isOwnFile(p) {
		return fmt.Errorf("invalid file path %q", p)
	}
	return nil
}

func isHex(s string, n int) bool {
	if len(s) != n {
		return false
	}
	for _, c := range s {
		if (c < '0' || c > '9') && (c < 'a' || c > 'f') {
			return false
		}
	}
	return true
}

// ProblemKind classifies a difference between a tree and its manifest.
type ProblemKind int

const (
	// ProblemMissing: listed in the manifest, absent from the tree.
	ProblemMissing ProblemKind = iota + 1
	// ProblemExtra: present in the tree, not listed in the manifest.
	ProblemExtra
	// ProblemModified: content differs from the recorded hash.
	ProblemModified
)

func (k ProblemKind) String() string {
	switch k {
	case ProblemMissing:
		return "missing"
	case ProblemExtra:
		return "not in manifest"
	case ProblemModified:
		return "modified"
	default:
		return "ProblemKind(" + strconv.Itoa(int(k)) + ")"
	}
}

// Problem is one difference between a tree and its manifest.
type Problem struct {
	Path string
	Kind ProblemKind
}

func (p Problem) String() string { return p.Path + ": " + p.Kind.String() }

// Verify compares the files under dir with dir/MANIFEST.json and returns every
// difference, sorted by path. A nil slice means the tree matches its manifest.
func Verify(dir string) ([]Problem, error) {
	m, err := Load(dir)
	if err != nil {
		return nil, err
	}
	actual, err := HashTree(dir)
	if err != nil {
		return nil, err
	}

	want := make(map[string]File, len(m.Files))
	for _, f := range m.Files {
		want[f.Path] = f
	}
	var problems []Problem
	for _, f := range actual {
		recorded, ok := want[f.Path]
		switch {
		case !ok:
			problems = append(problems, Problem{Path: f.Path, Kind: ProblemExtra})
		case recorded.SHA256 != f.SHA256:
			problems = append(problems, Problem{Path: f.Path, Kind: ProblemModified})
		}
		delete(want, f.Path)
	}
	for p := range want {
		problems = append(problems, Problem{Path: p, Kind: ProblemMissing})
	}
	sort.Slice(problems, func(i, j int) bool { return problems[i].Path < problems[j].Path })
	return problems, nil
}
